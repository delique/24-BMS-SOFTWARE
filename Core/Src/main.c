    // check the voltages
    // start the CV Conversion
    if (flagStartCVConversion)
    {
      wakeup_idle(TOTAL_IC);
      LTC6811_adcv(MD_27KHZ_14KHZ, DCP_DISABLED, CELL_CH_ALL);
      flagStartCVConversion = false;
    }

    // read the CB conversion
    if (flagReadCVConversion)
    {
      wakeup_idle(TOTAL_IC);
      cvError = LTC6811_rdcv(CELL_CH_ALL, TOTAL_IC, bms_ic);
      for (int j = 0; j < TOTAL_IC; j++)
      {
        for (int i = 0; i < 12; i++)
          voltages[i + 12 * j] = bms_ic[j].cells.c_codes[i] * 0.0001;
      }
      flagReadCVConversion = false;
    }

